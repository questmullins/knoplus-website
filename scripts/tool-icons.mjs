// Writes nextjs-elements/data/tool-icons.ts: the Simple Icons (CC0) path and brand colour for every `icon` slug in data/toolkit.ts.
// Run from the repository root:  npm i --no-save simple-icons && node scripts/tool-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";
import * as icons from "simple-icons";

const source = readFileSync("nextjs-elements/data/toolkit.ts", "utf8");
const slugs = [...new Set([...source.matchAll(/icon: "([a-z0-9]+)"/g)].map(match => match[1]))];
const bySlug = Object.fromEntries(Object.values(icons).filter(icon => icon?.slug).map(icon => [icon.slug, icon]));
const missing = slugs.filter(slug => !bySlug[slug]);
if (missing.length) throw new Error(`No Simple Icons logo for: ${missing.join(", ")}`);

const lines = slugs.sort().map(slug => `  ${JSON.stringify(slug)}: { hex: "#${bySlug[slug].hex}", path: ${JSON.stringify(bySlug[slug].path)} },`);
writeFileSync("nextjs-elements/data/tool-icons.ts",
  `// Generated by scripts/tool-icons.mjs from Simple Icons (CC0, simpleicons.org). Do not edit by hand.\n` +
  `export const toolIcons: Record<string, { hex: string; path: string }> = {\n${lines.join("\n")}\n};\n`);
console.log(`Wrote ${slugs.length} icons.`);
